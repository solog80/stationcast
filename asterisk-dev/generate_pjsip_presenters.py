#!/usr/bin/env python3
"""Generate PJSIP endpoint/auth/aor blocks for SIP presenters.

Run this on Edge2 (or copy the output to the Asterisk config dir):

  sudo python3 generate_pjsip_presenters.py --count 3

Writes:
  /opt/asterisk-dev/etc/pjsip-presenters.conf  (non-secret, include from pjsip.conf)
  /opt/asterisk-dev/presenters.env             (mode 600, name=password + numbers)

Re-running rotates every presenter password.
"""

import argparse
import pathlib
import secrets


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=3, help="number of presenters")
    ap.add_argument("--base", type=int, default=2001, help="first extension number")
    ap.add_argument("--context", default="presenters")
    ap.add_argument(
        "--output",
        default="/opt/asterisk-dev/etc/pjsip-presenters.conf",
    )
    ap.add_argument(
        "--creds",
        default="/opt/asterisk-dev/presenters.env",
    )
    args = ap.parse_args()

    blocks: list[str] = [
        "; Generated by generate_pjsip_presenters.py - safe to regenerate.",
        "; Endpoints register here; all join ConfBridge(7000).",
        "",
    ]
    creds: list[str] = [
        "# Generated by generate_pjsip_presenters.py (mode 600)",
        "# name=password | number=<extension> | context=<dialplan context>",
    ]

    for i in range(args.count):
        name = f"presenter{i + 1}"
        number = args.base + i
        label = f"Presenter {i + 1}"
        password = secrets.token_hex(16)

        blocks += [
            f"[{name}]",
            "type=endpoint",
            f"context={args.context}",
            "disallow=all",
            "allow=opus",
            "allow=g722",
            "allow=ulaw",
            "allow=alaw",
            "direct_media=no",
            "rtp_symmetric=yes",
            "force_rport=yes",
            "rewrite_contact=no",
            "rtp_timeout=30",
            f"auth={name}-auth",
            f"aors={name}",
            f'callerid="{label}" <{number}>',
            "",
            f"[{name}-auth]",
            "type=auth",
            "auth_type=userpass",
            f"username={name}",
            f"password={password}",
            "",
            f"[{name}]",
            "type=aor",
            "max_contacts=3",
            "remove_existing=yes",
            "qualify_frequency=30",
            "",
        ]
        creds.append(f"{name}={password} | number={number} | context={args.context}")

    output = pathlib.Path(args.output)
    output.write_text("\n".join(blocks) + "\n")
    output.chmod(0o640)

    cred_path = pathlib.Path(args.creds)
    cred_path.write_text("\n".join(creds) + "\n")
    cred_path.chmod(0o600)

    print(f"wrote {output} ({args.count} presenters)")
    print(f"wrote {cred_path} (mode 600; passwords not printed)")


if __name__ == "__main__":
    main()
